// Première lettre en capitale pour l'affichage (« mer Noire » → « Mer Noire »).
export const seaLabel = (name) => name.charAt(0).toUpperCase() + name.slice(1);

export const slug = (name) =>
  name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
